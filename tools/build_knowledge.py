"""Compile the chatbot's markdown knowledge base into js/knowledge.js for the
offline assistant, so the website and the Claude backend answer from the same
source of truth.

Run from the portfolio folder after editing portfolio-rag-chatbot/data/knowledge:
    python tools/build_knowledge.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KB_DIR = ROOT.parent / "portfolio-rag-chatbot" / "data" / "knowledge"
OUT = ROOT / "js" / "knowledge.js"
FRONTMATTER = re.compile(r"^---\s*\n(.*?)\n---\s*\n", re.S)
URL = re.compile(r"https?://[^\s,)]+")


def split_sentences(text: str) -> list[str]:
    out: list[str] = []
    for line in text.splitlines():
        line = re.sub(r"^\s*[-*]\s+", "", line).strip()
        if not line:
            continue
        # Protect abbreviations ("Prof. Dr.", "et al.") so they don't end a sentence.
        line = re.sub(r"\b(Prof|Dr|Mr|Ms|Mrs|al|e\.g|i\.e|vs|approx)\. ", lambda m: m.group(0)[:-1] + "@@", line)
        for s in re.split(r"(?<=[.!?])\s+(?=[A-Z0-9\"(])", line):
            s = s.replace("@@", " ").strip()
            if len(s) > 15:
                out.append(s)
    return out


def main() -> None:
    chunks = []
    for path in sorted(KB_DIR.glob("*.md")):
        raw = path.read_text(encoding="utf-8")
        meta: dict[str, str] = {}
        m = FRONTMATTER.match(raw)
        if m:
            for line in m.group(1).splitlines():
                if ":" in line:
                    k, v = line.split(":", 1)
                    meta[k.strip()] = v.strip()
            raw = raw[m.end():]
        for sec in re.split(r"^##\s+", raw, flags=re.M):
            sec = sec.strip()
            if not sec:
                continue
            heading, _, body = sec.partition("\n")
            if not body.strip():
                continue
            urls = URL.findall(body)
            gh = next((u.rstrip(".") for u in urls if "github.com/Data-Fenix/" in u), None)
            sentences = split_sentences(body)
            # Sentences that are only link lists are good for retrieval but poor answers.
            answerable = [s for s in sentences if not re.match(r"^(Repository|Repositories):", s) and "http" not in s]
            chunks.append(
                {
                    "id": f"{path.stem}#{len(chunks)}",
                    "source": path.stem,
                    "title": meta.get("title", path.stem),
                    "section": heading.strip(),
                    "url": gh or meta.get("url", ""),
                    "text": " ".join(sentences),
                    "sentences": answerable or sentences,
                }
            )
    OUT.write_text(
        "// Generated by tools/build_knowledge.py from portfolio-rag-chatbot/data/knowledge. Do not edit by hand.\n"
        f"window.PORTFOLIO_KB = {json.dumps(chunks, ensure_ascii=False, indent=1)};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.name}: {len(chunks)} sections, {sum(len(c['sentences']) for c in chunks)} sentences")


if __name__ == "__main__":
    main()
